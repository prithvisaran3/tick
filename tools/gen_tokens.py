#!/usr/bin/env python3
"""design/tokens.json + motion.json -> app/lib/design/tokens.g.dart, motion.g.dart, design/tokens.css"""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
t = json.loads((ROOT / "design/tokens.json").read_text())
m = json.loads((ROOT / "design/motion.json").read_text())
pal = t["palette"]

def dart_color(h): return "Color(0xFF" + h.lstrip("#").upper() + ")"
def camel(s):
    p = s.split("_"); return p[0] + "".join(x.title() for x in p[1:])

out = ["// GENERATED by tools/gen_tokens.py from design/tokens.json. DO NOT EDIT.",
       "// ignore_for_file: type=lint",
       "import 'dart:ui';", "",
       "abstract final class TickPalette {"]
for k, v in pal.items():
    out.append(f"  static const Color {camel(k)} = {dart_color(v)};")
out.append("}\n")
roles = list(t["themes"]["dark"].keys())
out.append("class TickColors {")
out.append("  const TickColors({" + ", ".join(f"required this.{r}" for r in roles) + "});")
for r in roles: out.append(f"  final Color {r};")
out.append("}\n")
for name, th in t["themes"].items():
    out.append(f"const TickColors tick{name.title()}Colors = TickColors(")
    for r in roles:
        out.append(f"  {r}: TickPalette.{camel(th[r])},")
    out.append(");\n")
out.append("class TickTypeSpec {\n  const TickTypeSpec(this.family, this.size, this.weight, this.height, this.tracking);\n"
           "  final String family; final double size; final int weight; final double height; final double tracking;\n}\n")
out.append("abstract final class TickFamilies {")
for k, v in t["type"]["families"].items(): out.append(f"  static const String {k} = '{v}';")
out.append("}\n")
out.append("abstract final class TickType {")
fam = t["type"]["families"]
for k, v in t["type"]["scale"].items():
    out.append(f"  static const TickTypeSpec {k} = TickTypeSpec('{fam[v['family']]}', {float(v['size'])}, {v['weight']}, {float(v['height'])}, {float(v['tracking'])});")
out.append("}\n")
out.append("abstract final class TickSpace {")
for k, v in t["space"].items(): out.append(f"  static const double {k} = {float(v)};")
out.append("}\n")
out.append("abstract final class TickRadius {")
for k, v in t["radius"].items(): out.append(f"  static const double {k} = {float(v)};")
out.append("}\n")
out.append("abstract final class TickLayout {")
for k, v in t["layout"].items(): out.append(f"  static const double {k} = {float(v)};")
out.append("}")
dst = ROOT / "app/lib/design"; dst.mkdir(parents=True, exist_ok=True)
(dst / "tokens.g.dart").write_text("\n".join(out) + "\n")

mo = ["// GENERATED by tools/gen_tokens.py from design/motion.json. DO NOT EDIT.",
      "// ignore_for_file: type=lint", "",
      "class TickSpringSpec {\n  const TickSpringSpec(this.stiffness, this.damping, this.mass);\n  final double stiffness; final double damping; final double mass;\n}\n",
      "abstract final class TickSprings {"]
for k, v in m["springs"].items():
    mo.append(f"  static const TickSpringSpec {k} = TickSpringSpec({float(v['stiffness'])}, {float(v['damping'])}, {float(v['mass'])});")
mo.append("}\n")
mo.append("abstract final class TickMotion {")
mo.append(f"  static const int reduceMotionFadeMs = {m['reduceMotion']['fadeMs']};")
mo.append(f"  static const double stickerTiltDeg = {float(m['moments']['sticker_slap']['tiltDeg'])};")
mo.append(f"  static const int countUpMs = {m['moments']['count_up']['durationMs']};")
mo.append(f"  static const int receiptLineIntervalMs = {m['moments']['receipt_print']['lineIntervalMs']};")
mo.append(f"  static const int receiptFirstLineDelayMs = {m['moments']['receipt_print']['firstLineDelayMs']};")
mo.append(f"  static const double caughtCommitPx = {float(m['moments']['caught_swipe']['commitDistancePx'])};")
mo.append(f"  static const int skeletonShimmerMs = {m['moments']['skeleton_shimmerMs']};")
mm = m["moments"]
mo.append(f"  static const int pageInMs = {mm['page']['inMs']};")
mo.append(f"  static const int pageOutMs = {mm['page']['outMs']};")
mo.append(f"  static const double pageFromOffsetX = {float(mm['page']['fromOffsetX'])};")
mo.append(f"  static const int sheetInMs = {mm['sheet_timing']['inMs']};")
mo.append(f"  static const int sheetOutMs = {mm['sheet_timing']['outMs']};")
mo.append(f"  static const double sheetSpringSeconds = {float(mm['sheet_timing']['springSeconds'])};")
mo.append(f"  static const int squareUpMs = {mm['square_up']['durationMs']};")
mo.append(f"  static const int staggerStepMs = {mm['list_stagger']['stepMs']};")
mo.append(f"  static const int staggerMaxItems = {mm['list_stagger']['maxItems']};")
mo.append(f"  static const double staggerFromOffsetY = {float(mm['list_stagger']['fromOffsetY'])};")
mo.append(f"  static const int settledHoldMs = {mm['settled']['holdMs']};")
mo.append(f"  static const int splashTotalMs = {mm['splash']['totalMs']};")
mo.append(f"  static const int splashDrawMs = {mm['splash']['drawMs']};")
mo.append(f"  static const int splashFadeMs = {mm['splash']['fadeMs']};")
mo.append(f"  static const int sceneMs = {mm['cinematic']['sceneMs']};")
mo.append(f"  static const int undoWindowMs = {mm['undo']['windowMs']};")
mo.append(f"  static const double swipeThresholdRatio = {float(mm['swipe_reveal']['thresholdRatio'])};")
mo.append("}")
(dst / "motion.g.dart").write_text("\n".join(mo) + "\n")

css = ["/* GENERATED by tools/gen_tokens.py. DO NOT EDIT. */", ":root{"]
for k, v in pal.items(): css.append(f"  --{k.replace('_','-')}: {v};")
for k, v in t["space"].items(): css.append(f"  --{k}: {v}px;")
for k, v in t["radius"].items(): css.append(f"  --r-{k}: {v}px;")
css.append("}")
for name, th in t["themes"].items():
    css.append(f"[data-theme='{name}']{{")
    for r, c in th.items(): css.append(f"  --{r}: var(--{c.replace('_','-')});")
    css.append("}")
for k, v in t["type"]["scale"].items():
    css.append(f".t-{k}{{font-family:'{fam[v['family']]}';font-size:{v['size']}px;font-weight:{v['weight']};line-height:{v['height']};letter-spacing:{v['tracking']}px}}")
ff = [("CabinetGrotesk", 500, "CabinetGrotesk-Medium"), ("CabinetGrotesk", 700, "CabinetGrotesk-Bold"),
      ("CabinetGrotesk", 800, "CabinetGrotesk-Extrabold"), ("CabinetGrotesk", 900, "CabinetGrotesk-Black"),
      ("Satoshi", 400, "Satoshi-Regular"), ("Satoshi", 500, "Satoshi-Medium"), ("Satoshi", 700, "Satoshi-Bold"), ("Satoshi", 900, "Satoshi-Black")]
fonts = [f"@font-face{{font-family:'{f}';font-weight:{w};src:url('../app/assets/fonts/{fn}.ttf')}}" for f, w, fn in ff]
fonts.append("@font-face{font-family:'GeistMono';font-weight:100 900;src:url('../app/assets/fonts/GeistMono-Variable.ttf')}")
(ROOT / "design/tokens.css").write_text("\n".join(fonts + css) + "\n")
print("tokens generated")
