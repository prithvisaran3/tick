#!/usr/bin/env python3
"""Generate supabase/tests/money_rules.sql from api/tests/data/money_rules.json (the fixture the Python tests use), so the SQL money rules
and the Python classifier are checked against the SAME rows and expectations. `--check` fails if the committed file is stale."""
import json, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
FIX = json.loads((ROOT / "api/tests/data/money_rules.json").read_text())
OUT = ROOT / "supabase/tests/money_rules.sql"

def q(s): return "'" + str(s).replace("'", "''") + "'"

def build() -> str:
    rows = FIX["rows"]
    L = ["-- GENERATED by tools/gen_money_sql.py from api/tests/data/money_rules.json. Do not edit by hand. Always rolls back.",
         "do $$", "declare", "  a uuid := gen_random_uuid(); b uuid := gen_random_uuid(); fails text := ''; n int; j jsonb; r record; ids jsonb := '{}'; v uuid; k text; cat uuid;",
         "begin",
         "  insert into auth.users (id, aud, role, email) values (a, 'authenticated', 'authenticated', 'a@test.local'), (b, 'authenticated', 'authenticated', 'b@test.local');"]
    for key, acc in FIX["accounts"].items():
        L.append(f"  insert into public.accounts (user_id, name, type, mask, institution) values (a, {q(acc['institution'] + ' ' + acc['mask'])}, {q(acc['type'])}, {q(acc['mask'])}, {q(acc['institution'])}) returning id into v; ids := ids || jsonb_build_object({q(key)}, v);")
    for r in rows:
        day = f"2026-10-{r['day']:02d}" if r["day"] > 15 else f"2026-11-{r['day']:02d}"
        flow = "null" if r["flow"] is None else q(r["flow"])
        L.append(f"  select id into cat from public.categories where user_id = a and name = {q(r['cat'])};")
        L.append(f"  insert into public.transactions (user_id, account_id, amount_cents, occurred_at, merchant_raw, merchant_clean, category_id, flow, plaid_transaction_id) "
                 f"values (a, (ids->>{q(r['acct'])})::uuid, {r['cents']}, '{day} 15:00Z', {q(r['desc'])}, {q(r['desc'])}, cat, {flow}, {q(r['k'])});")
    L.append("  perform set_config('request.jwt.claims', json_build_object('sub', a, 'role', 'authenticated')::text, true);")
    L.append("  set local role authenticated;")
    L.append("  if (select count(*) from public.categories where name = 'Friends and family') = 0 then fails := fails || 'Friends and family category missing; '; end if;")
    for r in rows:
        L.append(f"  select out_c, in_c into r from public.tick_classified(a, null, null) where id = (select id from public.transactions where plaid_transaction_id = {q(r['k'])});")
        L.append(f"  if r.out_c <> {r['out']} or r.in_c <> {r['in']} then fails := fails || format('{r['k']}: out %s in %s, want {r['out']}/{r['in']}; ', r.out_c, r.in_c); end if;")
    t = FIX["totals"]
    L.append("  j := public.tick_flows(null, null);")
    L.append(f"  if (j->>'in')::bigint <> {t['in']} or (j->>'out')::bigint <> {t['out']} or (j->>'net')::bigint <> {t['in'] - t['out']} then fails := fails || format('totals %s; ', j); end if;")
    # property: day totals of the page == the sum of that day's visible rows, under several filters
    L.append("""  -- Property: every day total and the month total equal the sum of the rows you can see under the active filter.
  for r in select * from (values (null::text[], null::text), (array['credit'], null), (array['checking'], null), (null, 'zelle'), (array['loan','savings'], null)) f(types, q) loop
    j := public.tick_activity_page(null, null, r.types, null, null, r.q, false, false, null, null, 100);
    for k in select jsonb_object_keys(j->'day_totals') loop
      select coalesce(sum(in_c - out_c), 0) into n from public.tick_filtered(null, null, r.types, null, null, r.q, false, false) x where (x.occurred_at at time zone 'America/New_York')::date = k::date;
      if n <> (j->'day_totals'->>k)::bigint then fails := fails || format('day %s under filter %s: header %s, rows %s; ', k, r.types, j->'day_totals'->>k, n); end if;
    end loop;
    select coalesce(sum(in_c - out_c), 0) into n from public.tick_filtered(null, null, r.types, null, null, r.q, false, false);
    if n <> (public.tick_flows(null, null, r.types, null, null, r.q) ->> 'net')::bigint then fails := fails || format('month total under filter %s; ', r.types); end if;
  end loop;
  -- B sees none of it.
  perform set_config('request.jwt.claims', json_build_object('sub', b, 'role', 'authenticated')::text, true);
  if (public.tick_flows(null, null) ->> 'count')::int <> 0 then fails := fails || 'B sees A rows; '; end if;
  reset role;
  if fails <> '' then raise exception 'MONEY_TESTS_FAILED: %', fails; end if;
  raise exception 'MONEY_TESTS_PASSED';
end $$;""")
    return "\n".join(L) + "\n"

if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else "money_rules.sql is stale: run tools/gen_money_sql.py")
    OUT.write_text(text); print("wrote", OUT)
